# ── the real anchors ────────────────────────────────────────────────────────────
def anchors() -> list[dict]:
    configs = [yaml.safe_load(p.read_text()) for p in sorted(Path("config/data").glob("*.yaml"))]
    return [c for c in configs if c.get("loader")]


ANCHORS = anchors()


def anchor_present(cfg: dict) -> bool:
    root = Path(cfg["source"].get("place_in", "data/raw"))
    return (root / (cfg["source"].get("transactions_file") or cfg["source"]["file"])).exists()


@pytest.mark.parametrize("cfg", ANCHORS, ids=[c["name"] for c in ANCHORS])
def test_features_build_over_the_real_anchor_at_a_workable_speed(cfg):
    """Ticket 07's first line. The measured numbers are in `docs/features.md`; this is the floor.

    Deliberately a floor and not a target: a throughput assertion tuned to one laptop is a flaky
    test. It is here to catch a change that makes the builder quadratic, which is the regression
    that would actually hurt.
    """
    if not anchor_present(cfg):
        pytest.skip(f"{cfg['name']} not downloaded")

    rows = loaders.load_from_config({**cfg, "sample": {"sample_fraction": 0.02}})
    builder = FeatureBuilder(stateful=True)
    start = time.perf_counter()
    X = builder.transform(rows, update=True)
    elapsed = time.perf_counter() - start

    assert X.shape == (len(rows), len(feature_names()))
    assert np.isfinite(X.to_numpy()).all(), "a non-finite feature will poison any scaler"
    assert len(rows) / elapsed > MIN_ROWS_PER_SECOND, (
        f"{cfg['name']}: {len(rows) / elapsed:,.0f} rows/s is below the {MIN_ROWS_PER_SECOND:,} "
        "floor — the builder has probably gone quadratic"
    )


@pytest.mark.parametrize("cfg", ANCHORS, ids=[c["name"] for c in ANCHORS])
def test_the_beneficiary_block_is_alive_on_every_real_anchor(cfg):
    """The one thing ticket 02 said ticket 07 had to get right, asserted on the real files.

    PaySim has no sender history, so a feature set built on the `src` side is built on nothing.
    The check is therefore not "the table has columns" but "the beneficiary columns move".
    """
    if not anchor_present(cfg):
        pytest.skip(f"{cfg['name']} not downloaded")

    rows = loaders.load_from_config({**cfg, "sample": {"sample_fraction": 0.02}})
    builder = FeatureBuilder(stateful=True)
    coverage = builder.coverage(builder.transform(rows, update=True))
    beneficiary = coverage[coverage["group"] == "beneficiary-inbound"]
    assert not beneficiary["dead"].any(), (
        f"{cfg['name']}: dead beneficiary features "
        f"{list(beneficiary[beneficiary['dead']].index)} — the anchor has no fan-in to learn from"
    )
