def test_the_amount_z_score_survives_an_account_that_always_pays_the_same_amount():
    """A subscription, an EMI, a salary. The naive variance turns rounding error into a signal.

    `E[x^2] - E[x]^2` over amounts of 10,000,000 has the two terms agreeing to fifteen digits, so
    what is left is noise — and `src_amount_z` divides by it. An account that has paid exactly
    the same amount forty times has a standard deviation of zero, and a detector must not be told
    that its forty-first identical payment is unusual.
    """
    builder = FeatureBuilder()
    rows = [txn(f"s{i}", i * 3_600, "payer", "biller", 10_000_000.0) for i in range(40)]
    rows.append(txn("same_again", 40 * 3_600, "payer", "biller", 10_000_000.0))
    X = builder.transform(rows)
    assert X.loc["same_again", "src_out_amount_std"] == 0.0
    assert X.loc["same_again", "src_amount_z"] == 0.0
    assert X.loc["same_again", "src_out_amount_mean"] == 10_000_000.0


def test_the_standard_deviation_is_accurate_on_large_near_constant_amounts():
    """The same trap one step less obvious: a tiny but real spread on a large amount."""
    rng = np.random.default_rng(3)
    amounts = np.abs(rng.normal(1e7, 1.0, 500)) + 0.01
    rows = [txn(f"n{i}", i * 60, "payer", "biller", float(a)) for i, a in enumerate(amounts)]
    X = FeatureBuilder().transform(rows)
    got = X.iloc[-1]["src_out_amount_std"]
    want = float(np.std(amounts[:-1]))
    assert got == pytest.approx(want, rel=1e-6), f"{got} != {want} — unstable variance is back"


