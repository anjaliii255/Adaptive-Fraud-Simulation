#: Floor for the real-anchor timing test. Ten times slower than measured, so it catches a
#: quadratic regression and never fires on a busy laptop. The measured numbers live in
#: `docs/features.md`, regenerated by `make features`.
MIN_ROWS_PER_SECOND = 10_000


def txn(txn_id: str, offset_s: float, src: str, dst: str, amount: float = 100.0, **kw):
    return Transaction(
        txn_id=txn_id,
        ts=T0 + timedelta(seconds=offset_s),
        src=src,
        dst=dst,
        amount=amount,
        rail=kw.pop("rail", Rail.A2A),
        **kw,
    )


def random_txns(n: int, seed: int, offset_s: float = 0.0, prefix: str = "t", entities: int = 10):
    """Dense random traffic over a small population — every entity both pays and is paid."""
    rng = np.random.default_rng(seed)
    ids = [f"e{i}" for i in range(entities)]
    rows = []
    for i in range(n):
        src, dst = str(rng.choice(ids)), str(rng.choice(ids))
        if src == dst:
            dst = ids[-1] if src != ids[-1] else ids[0]
        rows.append(
            Transaction(
                txn_id=f"{prefix}{i:05d}",
                ts=T0 + timedelta(seconds=offset_s + float(rng.integers(0, 600_000))),
                src=src,
                dst=dst,
                amount=round(float(rng.lognormal(5.0, 1.2)), 2),
                rail=[Rail.A2A, Rail.CARD, Rail.UPI][int(rng.integers(0, 3))],
                device_id=f"dev{int(rng.integers(0, 4))}" if rng.random() < 0.8 else None,
                is_fraud=bool(rng.random() < 0.1),
            )
        )
    return rows


# ── the reference implementation ────────────────────────────────────────────────
def reference_rows(txns: list[Transaction], windows_s=VELOCITY_WINDOWS_S) -> np.ndarray:
    """The same 56 features, computed the obvious way: filter the prior rows and add them up.

    Deliberately O(n^2) and deliberately dumb. Its whole value is that it shares no code with
    the implementation, so an off-by-one in a bisect shows up as a number, not as a silence.
    """
    order = sorted(range(len(txns)), key=lambda i: txns[i].ts)
    out: list[list[float]] = [[]] * len(txns)
    seen: list[Transaction] = []
    for i in order:
        t = txns[i]
        ts = t.ts.timestamp()
        prior = [p for p in seen if p.ts.timestamp() <= ts]
        s_out = [(p.ts.timestamp(), p.amount, p.dst) for p in prior if p.src == t.src]
        s_in = [(p.ts.timestamp(), p.amount, p.src) for p in prior if p.dst == t.src]
        d_in = [(p.ts.timestamp(), p.amount, p.src) for p in prior if p.dst == t.dst]
        d_out = [(p.ts.timestamp(), p.amount, p.dst) for p in prior if p.src == t.dst]
        pair = [p.ts.timestamp() for p in prior if p.src == t.src and p.dst == t.dst]

        def window(events, w, now=ts):
            return [e for e in events if now - w <= e[0] <= now]

        hour, weekday, amount = t.ts.hour, t.ts.weekday(), t.amount
        f = [
            amount,
            float(np.log1p(amount)),
            hour + t.ts.minute / 60.0,
            float(hour < 6),
            float(weekday),
            float(weekday >= 5),
            float(t.rail.value == "card"),
            float(t.rail.value == "upi"),
            float(t.rail.value == "a2a"),
            float(abs(amount - round(amount, -2)) < 1e-9),
            float(9_000 <= amount < 10_000),
            float(900 <= amount < 1_000),
        ]
        for w in windows_s:
            r = window(s_out, w)
            f += [float(len(r)), sum(e[1] for e in r), float(len({e[2] for e in r}))]

        amounts = [e[1] for e in s_out]
        mean = sum(amounts) / len(amounts) if amounts else 0.0
        std = float(np.std(amounts)) if len(amounts) > 1 else 0.0
        f += [
            float(len(amounts)),
            ts - max(e[0] for e in s_out) if s_out else NEVER,
            mean,
            std,
            (amount - mean) / std if std > 0 else 0.0,
            amount / mean if mean else 1.0,
            float(len({e[2] for e in s_out})),
            ts - min(e[0] for e in s_out + s_in) if (s_out or s_in) else NEVER,
        ]
        for w in windows_s:
            r = window(d_in, w)
            f += [float(len(r)), sum(e[1] for e in r), float(len({e[2] for e in r}))]

        in_amounts = [e[1] for e in d_in]
        mean_in = sum(in_amounts) / len(in_amounts) if in_amounts else 0.0
        std_in = float(np.std(in_amounts)) if len(in_amounts) > 1 else 0.0
        f += [
            float(len(in_amounts)),
            float(len({e[2] for e in d_in})),
            ts - max(e[0] for e in d_in) if d_in else NEVER,
            mean_in,
            (amount - mean_in) / std_in if std_in > 0 else 0.0,
            float(not d_in),
            ts - min(e[0] for e in d_in + d_out) if (d_in or d_out) else NEVER,
        ]

        recent_in = window(s_in, DWELL_WINDOW_S)
        in_sum = sum(e[1] for e in recent_in)
        out_sum = sum(e[1] for e in window(s_out, DWELL_WINDOW_S))
        f += [
            float(len(recent_in)),
            in_sum,
            ts - max(e[0] for e in s_in) if s_in else NEVER,
            out_sum / in_sum if in_sum > 0 else 0.0,
            float(len(window(d_out, DWELL_WINDOW_S))),
        ]
        f += [float(not pair), float(len(pair)), ts - max(pair) if pair else NEVER]

        devices: dict[str, float] = {}
        for p in prior:
            if p.src == t.src and p.device_id:
                devices[p.device_id] = min(devices.get(p.device_id, 1e18), p.ts.timestamp())
        first = devices.get(t.device_id) if t.device_id else None
        f += [
            float(len(devices)),
            float(t.device_id is not None and first is None),
            ts - first if first is not None else NEVER,
        ]
        out[i] = f
        seen.append(t)
    return np.array(out, dtype="float64")


def assert_matches_reference(X: pd.DataFrame, expected: np.ndarray, names: list[str]) -> None:
    got = X.to_numpy()
    bad = ~np.isclose(got, expected, rtol=1e-9, atol=1e-9)
    if bad.any():
        col = int(np.unique(np.where(bad)[1])[0])
        row = int(np.where(bad[:, col])[0][0])
        raise AssertionError(
            f"{int(bad.sum())} value(s) disagree with the reference, "
            f"first at row {row} column {names[col]!r}: {got[row, col]!r} != {expected[row, col]!r}"
        )


def test_every_column_matches_a_brute_force_reference():
    """The load-bearing test: the fast path and the obvious path agree on all 56 columns."""
    rows = random_txns(400, seed=7)
    builder = FeatureBuilder()
    assert_matches_reference(builder.transform(rows), reference_rows(rows), builder.feature_names)


def test_the_reference_also_holds_when_the_builder_carries_state_between_batches():
    """Statefulness must not be a second, subtly different implementation."""
    first, second = random_txns(200, seed=11), random_txns(200, seed=12, prefix="u")
    builder = FeatureBuilder(stateful=True)
    builder.transform(first)
    X = builder.transform(second)
    expected = reference_rows(first + second)[len(first) :]
    assert_matches_reference(X, expected, builder.feature_names)


# ── causality ───────────────────────────────────────────────────────────────────
def test_a_feature_does_not_change_when_later_rows_are_appended():
    """The ticket's property test, over random traffic rather than one hand-picked row.

    This is the failure mode the whole module exists to avoid: an offline table that looks
    excellent because it was built with knowledge no scorer would have had.
    """
    history = random_txns(150, seed=21)
    probe = random_txns(50, seed=23, prefix="p")  # same window as the history
    later = random_txns(150, seed=22, offset_s=700_000, prefix="z")  # strictly afterwards

    builder = FeatureBuilder(stateful=True)
    builder.transform(history, update=True)
    before = builder.transform(probe, update=False)

    builder.transform(later, update=True)  # the future arrives
    after = builder.transform(probe, update=False)

    assert_matches_reference(after, before.to_numpy(), builder.feature_names)


def test_one_probe_row_is_unmoved_by_everything_that_happens_after_it():
    builder = FeatureBuilder(stateful=True)
    history = [txn(f"h{i}", i * 600, "s1", "d1", 100.0 + i) for i in range(8)]
    probe = txn("probe", 9 * 600, "s1", "d1", 250.0)
    builder.transform(history, update=True)
    before = builder.transform([probe], update=False)

    builder.transform([txn(f"late{i}", 20_000 + i * 600, "s1", "d1") for i in range(6)])
    assert builder.transform([probe], update=False).equals(before)


def test_scoring_does_not_mutate_feature_state():
    """Ask the same question twice, get the same answer — even with a stateful builder."""
    builder = FeatureBuilder(stateful=True)
    rows = random_txns(120, seed=31)
    builder.transform(rows, update=True)

    first = builder.transform(rows, update=False)
    second = builder.transform(rows, update=False)
    assert first.equals(second)

    # and the committed history is byte-identical afterwards, not merely close
    committed = builder.transform(random_txns(40, seed=32, prefix="q"), update=True)
    builder_b = FeatureBuilder(stateful=True)
    builder_b.transform(rows, update=True)
    assert committed.equals(builder_b.transform(random_txns(40, seed=32, prefix="q")))


