"""■ B — the feature table is causal, it is documented, and it is built on the side that has data.

Ticket 07's three failure modes, in the order they cost the most:

  * **A feature that peeks forward.** This repo has already been bitten: the first pass found
    velocity windows reading rows from the future, and most of the apparent signal was leakage.
    So causality gets property tests and a brute-force cross-check, not a code review.
  * **A feature that is quietly empty.** PaySim has no sender history, so a third of this table
    is structurally dead on that anchor. A dead column reads exactly like a feature the model
    has, and it is not one — so the emptiness is measured, not assumed.
  * **A feature nobody can explain.** Every column carries a one-line rationale in the registry
    and `docs/features.md` is generated from it, so the two cannot drift apart.

The brute-force reference below is the load-bearing test. `FeatureBuilder` computes every column
by bisecting prefix-summed arrays, which is fast and is exactly the kind of code that goes wrong
by one index in a way no unit test notices. `reference_rows` computes the same 56 numbers the
obvious slow way — filter the prior rows, then add them up — and the two must agree exactly.
"""

